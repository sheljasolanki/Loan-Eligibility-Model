"""Exports the model's data files to webui/data.js (plain JS, no build step) so the web app runs the same rules as src/eligibility.py.

Writes LOAN_DATA (matrix, rate tiers, estimate bounds, assumptions), TEST_PROFILES, SOURCES (every rule with its source)
and, if docs/insights.json exists, INSIGHTS. Run after scripts/long_to_matrix.py, scripts/build_estimate_bounds.py
and scripts/simulate.py.
"""
import csv, json, os, sys
ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
sys.path.insert(0, os.path.join(ROOT, "src"))
import eligibility as E


def rows(name):
    with open(os.path.join(ROOT, "data", name), encoding="utf-8") as f:
        return list(csv.DictReader(f))


matrix = rows("lender_rules_matrix.csv")
for r in matrix:
    for k, v in r.items():
        if k not in E.TEXT_COLS:
            r[k] = float(v) if v not in ("", None) else None
tiers = [dict(t, cibil_min=float(t["cibil_min"]), cibil_max=float(t["cibil_max"]), rate_pct=float(t["rate_pct"])) for t in rows("rate_tiers.csv")]
bounds = [dict(b, base=float(b["base"]), strict=float(b["strict"]), lenient=float(b["lenient"])) for b in rows("estimate_bounds.csv")]
assumptions = rows("assumptions.csv")
sources = [{k: r[k] for k in ("lender_id", "rule_name", "rule_value", "unit", "source_type", "source_url", "accessed_on", "how_derived_or_evidence")}
           for r in rows("lender_rules_long.csv")]
profiles = json.load(open(os.path.join(ROOT, "tests", "test_profiles.json")))
ins_path = os.path.join(ROOT, "docs", "insights.json")
insights = json.load(open(ins_path)) if os.path.exists(ins_path) else None

out = os.path.join(ROOT, "webui", "data.js")
with open(out, "w", encoding="utf-8") as f:
    f.write("// Auto-generated by scripts/export_ui_data.py -- do not edit by hand.\n")
    f.write("const LOAN_DATA = " + json.dumps({"matrix": matrix, "tiers": tiers, "bounds": bounds, "assumptions": assumptions}) + ";\n")
    f.write("const SOURCES = " + json.dumps(sources) + ";\n")
    f.write("const TEST_PROFILES = " + json.dumps(profiles) + ";\n")
    f.write("const INSIGHTS = " + json.dumps(insights) + ";\n")
print(f"wrote {out}: {len(matrix)} lenders, {len(tiers)} tier rows, {len(bounds)} bounds, {len(sources)} rules, {len(profiles)} profiles, insights={'yes' if insights else 'no'}")
